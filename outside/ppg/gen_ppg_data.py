"""The PPG module's data, from local images of the PPG Wave 2.2 that are never committed (Saadet's tools/gen_ppg_waves.py
and tools/gen_ppg_factory.py, Saadet d4ae975, as one script beside the module):

    ppg_rom.h      the wave EPROMs' directory and 256 half-cycle waves, the V5 OS's envelope rate tables, WAVETABLE 31's
                   natural sounds (the piano from the V3 dump's EPROM 8, the saxophone from the V5 OS image)
    ppg_presets.h  the module's PRST rows (MOD3_PRESETS_PATCH): INIT WAVE, then the 2.2's 100 factory programs, preset
                   k + 1 = program k, each whole (both groups, KEYB, SPLIT) in ppg_patch.h's byte order

The images are PPG's (Palm Products GmbH): both headers land beside this script and are gitignored (outside/ppg/
.gitignore). They come from PPG_PRIVATE (a folder), else Saadet's checkout beside Melodee's (../saadet/private/ppg):
    ppg22-waves.bin, ppg22-os-v5.bin, dumps/ppg22v3.zip, ppg22-factory.syx, ppg22-factory-names.txt
The wave image and the OS image are required (the module refuses to build without them, as Saadet's engine does); the
natural sounds and the factory bank are optional (without them TABLE 31 is silent, the presets INIT alone).

    python3 gen_ppg_data.py            (writes the two headers beside it)"""
import hashlib
