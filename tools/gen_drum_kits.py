"""assets/drums/kits.bin + kits.json (tools/drum_kit_make.py) -> the header drum_real.c plays: every table in the resource
region (res.c). Levels and tones live in kits.json, so a by-ear change needs no re-encoding.

  tools/gen_drum_kits.py OUT.h
"""
import json, struct, sys
from pathlib import Path

A = Path(__file__).resolve().parent.parent / "assets/drums"
meta = json.loads((A / "kits.json").read_text())
blob = (A / "kits.bin").read_bytes()
words = struct.unpack(">%dI" % (len(blob) // 4), blob)
ids = {s["name"]: i for i, s in enumerate(meta["streams"])}
out = ["/* generated by tools/gen_drum_kits.py from assets/drums/kits.json: do not edit */",
       "#ifndef MELODEE_RES", "#define MELODEE_RES", "#endif",
       f"static const uint32_t DRK_SLICES[{len(words)}] MELODEE_RES = {{"]
for i in range(0, len(words), 10):
    out.append(" " + "".join(f"0x{w:08x}," for w in words[i:i + 10]))
out.append("};")
loops = [s for s in meta["streams"] if s["loop_at"]]
out.append(f"static const int32_t DRK_LOOPS[{len(loops)}][8] MELODEE_RES = {{")
out += ["  {" + ",".join(str(v) for v in s["state"]) + "}," for s in loops]
out.append("};")
out.append(f"static const drk_sample_t DRK_SAMPLES[{len(ids)}] MELODEE_RES = {{")
for s in meta["streams"]:
    st = loops.index(s) if s["loop_at"] else 0
    out.append(f"  {{{s['at']},{s['n']},{s['loop_at']},{s['loop_slice']},{s['inc']},{s['dark']},{st}}},  /* {s['name']} */")
out.append("};")
out.append(f"static const drk_map_t DRK_MAP[{len(meta['kits'])}][{len(meta['drums'])}] MELODEE_RES = {{")
for kit, m in meta["kits"].items():
    out.append(f"  {{  /* {kit} */")
    for d in meta["drums"]:
        s, alt, st, tone, lv, ms, pivot = m[d]
        out.append(f"    {{{ids[s]},{ids[alt] if alt else 255},{st},{tone},{lv},{ms},{pivot}}},  /* {d} */")
    out.append("  },")
out.append("};")
out.append("#ifdef DRK_TEST   /* each stream's samples as the encoder decoded them: CRC-32 (tests/drum_real_test.c) */")
out.append("static const uint32_t DRK_CRC[] = {" + ",".join(f"0x{s['crc']:08x}u" for s in meta["streams"]) + "};")
out.append('static const char *const DRK_NAME[] = {' + ",".join(f'"{s["name"]}"' for s in meta["streams"]) + "};")
out.append("#endif")
Path(sys.argv[1]).write_text("\n".join(out) + "\n")
