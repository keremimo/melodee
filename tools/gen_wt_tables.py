"""The WT engine's wavetable banks (firmware/src/eng_wt.c).

Each bank is 8 frames of a 256-point single-cycle wave, int16 Q15, one after the
other (8 x 256 x 2 = 4096 bytes per bank). MORPH walks the frames in one bank;
BANK picks the bank. Frames interpolate smoothly inside a bank (each frame's
first harmonic content is a superset of its neighbours'), so a sweep never
snaps. Amplitudes are normalised per bank (one peak at full scale), which the
engine's drive re-shapes.

Generated by tools/build.py into build/gen/melodee_wt.h as `const int16_t
WT_BANKS[WT_N][8 * 256]` (flash, XIP; the engine reads it directly).
"""
import math

# The banks (order matters: the presets and the web editor name them WT_BANK_NAMES).
def frame(parts, n=256):
    return [int(round(sum(a * math.sin(2 * math.pi * (k * i / n) + ph) for k, a, ph in parts) * 32767))
            for i in range(n)]


def norm(cycles):
    m = max(1e-9, max(abs(v) for v in cycles))
    k = 32767.0 / m
    return [int(round(v * k)) for v in cycles]


def morph_bank(start, stop, frames=8):
    """8 frames from spectrum `start` to `stop` (lists of (k, a, ph)), each frame a
    mix of the two ends so neighbouring frames share partials (smooth sweeps)."""
    out = []
    for f in range(frames):
        t = f / (frames - 1.0)
        mix = [(k, (1 - t) * a0 + t * a1, ph)
               for (k, a0, ph), (_, a1, _2) in zip(start, stop)]
        out.append(frame(mix))
    return norm([v for fr in out for v in fr])


def formant_bank(frame_fn, frames=8):
    return norm([v for f in range(frames) for v in frame_fn(f)])


BANKS = [
    # SAW->PULSE: the classic rich sweep
    morph_bank([(k, 1.0 / k, 0.0) for k in range(1, 17)],
               [(k, 1.0 / k if k % 2 else 0.0, 0.0) for k in range(1, 17)]),
    # RESO: a bump that walks up the harmonics (classic resonant sweeps)
    formant_bank(lambda f: frame([(k, 1.0 / k, 0.0) for k in range(1, 13)]
                                 + [(5 + f, 1.2, 0.0)])),
    # HOLLOW: odd harmonics fading in over a saw (clarinet -> square-ish)
    morph_bank([(k, 1.0 / k, 0.0) for k in range(1, 13)],
               [(k, 1.0 / k if k % 2 else 0.0, math.pi / 2) for k in range(1, 13)]),
    # VOX: two formant bumps moving in opposite directions
    formant_bank(lambda f: frame([(k, 1.0 / k, 0.0) for k in range(1, 17)]
                                 + [(4 + (f % 6), 0.9, 0.0), (11 - (f % 5), 0.7, math.pi)])),
    # DIGI: a bright edge that softens (saw -> rounded pulse)
    morph_bank([(k, 1.0 / k, 0.0) for k in range(1, 21)],
               [(k, 1.0 / (k * k) * (1 if k % 2 else 0), 0.0) for k in range(1, 21)]),
]

BANK_NAMES = ["SAW SQR", "RESO", "HOLLOW", "VOX", "DIGI"]


def main(path):
    L = ["/* generated by tools/gen_wt_tables.py */", "#pragma once", "#include <stdint.h>", ""]
    L += [f"#define WT_N {len(BANKS)}", f"#define WT_FRAMES 8u", f"#define WT_FRAME_PTS 256u", ""]
    L += ["static const char *const WT_BANK_NAMES[] = {" +
          ", ".join(f'"{n}"' for n in BANK_NAMES) + "};", ""]
    L += ["static const int16_t WT_BANKS[WT_N][WT_FRAMES * WT_FRAME_PTS] = {"]
    for b, bank in enumerate(BANKS):
        L.append(f"    /* {b}: {BANK_NAMES[b]} */")
        for i in range(0, len(bank), 12):
            L.append("    " + ", ".join(str(v) for v in bank[i:i + 12]) + ",")
    L.append("};")
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"gen_wt_tables: {len(BANKS)} banks x {8 * 256 * 2} B = {len(BANKS) * 8 * 256 * 2} B -> {path}")


if __name__ == "__main__":
    import sys
    main(sys.argv[1] if len(sys.argv) > 1 else "build/gen/melodee_wt.h")
